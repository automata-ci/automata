import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const repositoryRoot = fileURLToPath(new URL("../..", import.meta.url));
const contractPath = `${repositoryRoot}/crates/automata-ci-ui-renderer/contract.json`;
const generatedPath = `${repositoryRoot}/crates/automata-ci-ui-renderer/src/generated_contract.rs`;

const contract = JSON.parse(await readFile(contractPath, "utf8"));
assertPositiveInteger(contract.schemaVersion, "schemaVersion");
assertPositiveInteger(contract.maxRequestUtf8Bytes, "maxRequestUtf8Bytes");
assertPositiveInteger(contract.maxRenderedHtmlUtf8Bytes, "maxRenderedHtmlUtf8Bytes");
if (contract.schemaVersion !== 1) {
  throw new Error(`Unsupported renderer contract schema ${contract.schemaVersion}`);
}
if (contract.maxRenderedHtmlUtf8Bytes > 128 * 1024 * 1024) {
  throw new Error("Rendered HTML cap cannot exceed the default aggregate guest-memory cap");
}

const generated = `// @generated by scripts/ui/sync-render-contract.mjs; do not edit by hand.

/// Maximum UTF-8 wire size accepted for one serialized render request.
pub const MAX_RENDER_REQUEST_UTF8_BYTES: usize = ${rustInteger(contract.maxRequestUtf8Bytes)};

/// Maximum UTF-8 size returned for one rendered HTML document.
pub const MAX_RENDERED_HTML_UTF8_BYTES: usize = ${rustInteger(contract.maxRenderedHtmlUtf8Bytes)};
`;

if (process.argv.includes("--check")) {
  const existing = await readFile(generatedPath, "utf8");
  if (existing !== generated) {
    throw new Error(
      "Generated Rust renderer contract is stale; run scripts/ui/sync-render-contract.mjs",
    );
  }
} else {
  await writeFile(generatedPath, generated, "utf8");
}

function assertPositiveInteger(value, name) {
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`Renderer contract ${name} must be a positive safe integer`);
  }
}

function rustInteger(value) {
  return value.toLocaleString("en-US").replaceAll(",", "_");
}
